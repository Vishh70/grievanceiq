// src/services/historicalGroupingRepairService.js
const supabase = require('../config/supabase');
const { ComplaintGraphService } = require('./complaintGraphService');
const {
  generateCivicIssueTitle,
  calculateRepresentativeLocation,
  aggregatePriority
} = require('./civicIssueService');

/**
 * Service to identify and repair historical Civic Issues incorrectly grouped
 * using 'Related' edges or over-merged transitive chains.
 *
 * FR05: Only verified Duplicate relationships determine incident identity.
 * Related complaints must remain separate Civic Issues.
 */
class HistoricalGroupingRepairService {

  /**
   * Scans existing Civic Issues to identify any that contain multiple
   * disjoint duplicate clusters (i.e. joined via Related edges or over-merged).
   *
   * @param {object} options
   * @param {boolean} options.dryRun - When true, computes repair plan without modifying database
   * @returns {Promise<object>} Structured audit report and repair plan
   */
  async analyzeHistoricalGroupings(options = { dryRun: true }) {
    const dryRun = options.dryRun !== false;

    // 1. Fetch all non-merged Civic Issues that have more than 1 complaint
    const { data: issues, error: issuesErr } = await supabase
      .from('civic_issues')
      .select('id, title, primary_category, priority, location_lat, location_lng, complaint_ids, status')
      .neq('status', 'Merged');

    if (issuesErr) {
      console.error('[HistoricalRepair] Error fetching civic issues:', issuesErr.message);
      throw new Error(`Failed to fetch civic issues for historical audit: ${issuesErr.message}`);
    }

    const multiComplaintIssues = (issues || []).filter(
      issue => Array.isArray(issue.complaint_ids) && issue.complaint_ids.length > 1
    );

    const issuesNeedingRepair = [];
    let properlyGroupedCount = 0;

    for (const issue of multiComplaintIssues) {
      const complaintIds = issue.complaint_ids;

      // 2. Fetch full complaint records for this issue
      const { data: complaints, error: compErr } = await supabase
        .from('complaints')
        .select('id, category, priority, location_lat, location_lng, created_at, civic_issue_id')
        .in('id', complaintIds);

      if (compErr || !complaints || complaints.length === 0) {
        continue;
      }

      // 3. Fetch relationships connecting pairs within this issue's complaint set
      const { data: relationships, error: relErr } = await supabase
        .from('complaint_relationships')
        .select('id, source_complaint_id, target_complaint_id, relationship_type, confidence, reason');

      const relevantEdges = (relationships || []).filter(
        rel => complaintIds.includes(rel.source_complaint_id) && complaintIds.includes(rel.target_complaint_id)
      );

      // 4. Build graph using Duplicate-only policy
      const graphService = new ComplaintGraphService();
      graphService.buildGraph(
        complaints,
        relevantEdges.map(r => ({
          sourceId: r.source_complaint_id,
          targetId: r.target_complaint_id,
          relationship: r.relationship_type
        }))
      );

      const duplicateComponents = graphService.findConnectedComponents();

      // If more than 1 duplicate component exists within the issue, it was merged via Related edges!
      if (duplicateComponents.length > 1) {
        // Sort components by size descending so the largest cluster retains the original civic_issue_id
        duplicateComponents.sort((a, b) => b.length - a.length);

        const relatedEdgesFound = relevantEdges.filter(
          r => r.relationship_type && r.relationship_type.toLowerCase() === 'related'
        );

        issuesNeedingRepair.push({
          civicIssueId: issue.id,
          title: issue.title,
          originalComplaintCount: complaintIds.length,
          duplicateComponentsCount: duplicateComponents.length,
          duplicateComponents: duplicateComponents,
          relatedEdgesFound: relatedEdgesFound,
          proposedSplit: {
            retainedIssue: {
              id: issue.id,
              complaintIds: duplicateComponents[0]
            },
            newIssues: duplicateComponents.slice(1).map(compIds => ({
              complaintIds: compIds
            }))
          }
        });
      } else {
        properlyGroupedCount++;
      }
    }

    return {
      mode: dryRun ? 'DRY_RUN' : 'APPLY',
      totalMultiComplaintIssuesScanned: multiComplaintIssues.length,
      properlyGroupedCount: properlyGroupedCount,
      issuesNeedingRepairCount: issuesNeedingRepair.length,
      repairDetails: issuesNeedingRepair
    };
  }

  /**
   * Executes the repair plan generated by analyzeHistoricalGroupings.
   * Non-destructive:
   * - Retains the original civic issue for the largest duplicate cluster
   * - Creates new civic issues for disjoint clusters
   * - Repoints complaints to their correct duplicate-only civic issue
   * - Preserves all relationship records in complaint_relationships
   * - Preserves task assignments without dropping foreign key references
   *
   * @param {Array<object>} repairDetails - The repairDetails from analyzeHistoricalGroupings
   * @returns {Promise<object>} Summary of applied repairs
   */
  async applyHistoricalRepair(repairDetails) {
    if (!Array.isArray(repairDetails) || repairDetails.length === 0) {
      return {
        success: true,
        repairedCount: 0,
        newIssuesCreated: 0,
        repointedComplaintsCount: 0
      };
    }

    let repairedCount = 0;
    let newIssuesCreated = 0;
    let repointedComplaintsCount = 0;

    for (const repairItem of repairDetails) {
      const { civicIssueId, proposedSplit } = repairItem;
      const { retainedIssue, newIssues } = proposedSplit;

      // 1. Fetch complaints for the retained issue
      const { data: retainedComplaints } = await supabase
        .from('complaints')
        .select('*')
        .in('id', retainedIssue.complaintIds);

      if (retainedComplaints && retainedComplaints.length > 0) {
        const retainedTitle = generateCivicIssueTitle(retainedComplaints);
        const retainedLoc = calculateRepresentativeLocation(retainedComplaints);
        const retainedPriority = aggregatePriority(retainedComplaints);

        // Update the retained issue to only contain its verified duplicate complaints
        const { error: retainedUpdateErr } = await supabase
          .from('civic_issues')
          .update({
            title: retainedTitle,
            primary_category: retainedComplaints[0].category || 'Other',
            priority: retainedPriority,
            location_lat: retainedLoc.location_lat,
            location_lng: retainedLoc.location_lng,
            complaint_ids: retainedIssue.complaintIds,
            updated_at: new Date().toISOString()
          })
          .eq('id', civicIssueId);

        if (retainedUpdateErr) {
          console.error(`[HistoricalRepair] Error updating retained issue ${civicIssueId}:`, retainedUpdateErr.message);
          throw new Error(`Failed to update retained issue: ${retainedUpdateErr.message}`);
        }
      }

      // 2. For each separated component, create a new Civic Issue
      for (const newIssuePlan of newIssues) {
        const { data: separatedComplaints } = await supabase
          .from('complaints')
          .select('*')
          .in('id', newIssuePlan.complaintIds);

        if (!separatedComplaints || separatedComplaints.length === 0) continue;

        const newTitle = generateCivicIssueTitle(separatedComplaints);
        const newLoc = calculateRepresentativeLocation(separatedComplaints);
        const newPriority = aggregatePriority(separatedComplaints);
        const newCategory = separatedComplaints[0].category || 'Other';

        const { data: createdIssue, error: createErr } = await supabase
          .from('civic_issues')
          .insert([{
            title: newTitle,
            primary_category: newCategory,
            priority: newPriority,
            location_lat: newLoc.location_lat,
            location_lng: newLoc.location_lng,
            complaint_ids: newIssuePlan.complaintIds,
            status: 'Open',
            created_at: new Date().toISOString(),
            updated_at: new Date().toISOString()
          }])
          .select()
          .single();

        if (createErr) {
          console.error('[HistoricalRepair] Error creating new civic issue:', createErr.message);
          throw new Error(`Failed to create new civic issue during repair: ${createErr.message}`);
        }

        newIssuesCreated++;

        // 3. Repoint the complaints to the new civic issue
        const { error: repointErr } = await supabase
          .from('complaints')
          .update({
            civic_issue_id: createdIssue.id,
            updated_at: new Date().toISOString()
          })
          .in('id', newIssuePlan.complaintIds);

        if (repointErr) {
          console.error(`[HistoricalRepair] Error repointing complaints to ${createdIssue.id}:`, repointErr.message);
          throw new Error(`Failed to repoint complaints: ${repointErr.message}`);
        }

        repointedComplaintsCount += newIssuePlan.complaintIds.length;

        // 4. Repoint any tasks that correspond to this category/complaints if they exist
        try {
          const { data: existingTasks } = await supabase
            .from('tasks')
            .select('id, issue_type, department_id')
            .eq('civic_issue_id', civicIssueId)
            .eq('issue_type', newCategory);

          if (existingTasks && existingTasks.length > 0) {
            const taskIds = existingTasks.map(t => t.id);
            await supabase
              .from('tasks')
              .update({ civic_issue_id: createdIssue.id })
              .in('id', taskIds);
          }
        } catch (taskErr) {
          console.warn(`[HistoricalRepair] Non-fatal task migration warning:`, taskErr.message);
        }
      }

      repairedCount++;
    }

    return {
      success: true,
      repairedCount,
      newIssuesCreated,
      repointedComplaintsCount
    };
  }
}

module.exports = new HistoricalGroupingRepairService();

