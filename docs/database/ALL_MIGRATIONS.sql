  p_task_id UUID,
  p_new_status TEXT,
  p_user_email TEXT DEFAULT NULL,
  p_reason TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  v_current_status TEXT;
  v_civic_issue_id UUID;
  v_workstream_id UUID;
  v_unmet_task_id UUID;
  v_unmet_title TEXT;
  v_unmet_status TEXT;
  v_ws_new_status TEXT;
  v_ws_all_cancelled BOOLEAN;
