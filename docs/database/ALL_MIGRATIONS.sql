    loss_review,
    cost_matrix,
    selected_action,
    review_status,
    routed_reason,
    model_version,
    calibration_version,
    policy_version,
    is_latest
  )
  VALUES (
    p_source_id,
    p_target_id,
    p_relationship_type,
    p_raw_prob,
    p_cal_prob,
    COALESCE(p_is_calibrated, false),
    p_loss_accept,
