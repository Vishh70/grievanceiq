    RAISE EXCEPTION 'Invalid status transition from IN_PROGRESS to %', p_new_status;
  ELSIF v_current_status = 'COMPLETED' AND p_new_status NOT IN ('VERIFIED') THEN
    RAISE EXCEPTION 'Invalid status transition from COMPLETED to %', p_new_status;
  ELSIF v_current_status IN ('CANCELLED', 'VERIFIED') THEN
    RAISE EXCEPTION 'Task in % status cannot be transitioned to %', v_current_status, p_new_status;
  END IF;

  -- 2. Prerequisite enforcement when transitioning to IN_PROGRESS
  IF p_new_status = 'IN_PROGRESS' THEN
    SELECT t.id, t.title, t.status
    INTO v_unmet_task_id, v_unmet_title, v_unmet_status
    FROM public.task_dependencies td
    JOIN public.tasks t ON t.id = td.depends_on_task_id
    WHERE td.task_id = p_task_id
      AND t.status NOT IN ('COMPLETED', 'VERIFIED')
    LIMIT 1;

    IF FOUND THEN
      RAISE EXCEPTION 'Cannot start task. Prerequisite task % ("%") is not COMPLETED or VERIFIED (current status: %)',
        v_unmet_task_id, v_unmet_title, v_unmet_status;
    END IF;
  END IF;

  -- 3. Update Task
  UPDATE public.tasks 
  SET 
    status = p_new_status, 
    started_at = CASE WHEN p_new_status = 'IN_PROGRESS' AND v_current_status = 'PENDING' THEN now() ELSE started_at END,
    completed_at = CASE WHEN p_new_status = 'COMPLETED' THEN now() ELSE completed_at END,
    verified_at = CASE WHEN p_new_status = 'VERIFIED' THEN now() ELSE verified_at END,
    cancelled_at = CASE WHEN p_new_status = 'CANCELLED' THEN now() ELSE cancelled_at END,
    updated_at = now() 
  WHERE id = p_task_id;

  -- 4. Audit Log
  INSERT INTO public.task_status_history 
    (task_id, previous_status, new_status, changed_by, reason)
  VALUES 
    (p_task_id, v_current_status, p_new_status, COALESCE(p_user_email, 'system'), COALESCE(p_reason, 'Transitioned to ' || p_new_status));

  -- 5. Re-evaluate Workstream Status
  SELECT 
    bool_and(status = 'CANCELLED'),
    bool_and(status IN ('COMPLETED', 'VERIFIED', 'CANCELLED')),
    bool_and(status = 'PENDING')
  INTO v_ws_all_cancelled, v_ws_all_finished, v_ws_none_started
  FROM public.tasks
  WHERE workstream_id = v_workstream_id;
  
  IF v_ws_all_cancelled THEN v_ws_new_status := 'CANCELLED';
  ELSIF v_ws_all_finished THEN v_ws_new_status := 'COMPLETED';
  ELSIF NOT v_ws_none_started THEN v_ws_new_status := 'IN_PROGRESS';
  ELSE v_ws_new_status := 'PENDING';
  END IF;
  
  UPDATE public.workstreams 
  SET status = v_ws_new_status, updated_at = now() 
  WHERE id = v_workstream_id;

  -- 6. Re-evaluate Civic Issue Status
  -- Rule: A Civic Issue must not automatically be marked resolved merely because one department finishes.
  -- All required tasks across all workstreams must be completed or cancelled.
  SELECT 
    bool_and(status = 'CANCELLED'),
    bool_and(status IN ('COMPLETED', 'VERIFIED', 'CANCELLED')),
    bool_and(status = 'PENDING')
  INTO v_issue_all_cancelled, v_issue_all_finished, v_issue_none_started
  FROM public.tasks
  WHERE civic_issue_id = v_civic_issue_id;

  IF v_issue_all_cancelled THEN v_issue_new_status := 'CANCELLED';
  ELSIF v_issue_all_finished THEN v_issue_new_status := 'COMPLETED';
  ELSIF NOT v_issue_none_started THEN v_issue_new_status := 'IN_PROGRESS';
  ELSE v_issue_new_status := 'PENDING';
  END IF;

  UPDATE public.civic_issues 
  SET status = v_issue_new_status, updated_at = now() 
  WHERE id = v_civic_issue_id;

END;
$$;

CREATE OR REPLACE FUNCTION public.verify_civic_issue_resolution(
  p_civic_issue_id UUID,
  p_verifier_id UUID,
  p_notes TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
AS $$
DECLARE
  v_incomplete_count INT;
  v_total_tasks INT;
  v_verifier RECORD;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.civic_issues WHERE id = p_civic_issue_id) THEN
    RAISE EXCEPTION 'Civic Issue % not found', p_civic_issue_id;
  END IF;

  SELECT 
    COUNT(*),
    COUNT(*) FILTER (WHERE status NOT IN ('COMPLETED', 'VERIFIED', 'CANCELLED'))
  INTO v_total_tasks, v_incomplete_count
  FROM public.tasks
  WHERE civic_issue_id = p_civic_issue_id;

  IF v_total_tasks = 0 THEN
    RAISE EXCEPTION 'Civic Issue % has no tasks to verify', p_civic_issue_id;
  END IF;

  IF v_incomplete_count > 0 THEN
    RAISE EXCEPTION 'Cannot verify Civic Issue resolution. % incomplete task(s) remain across departments', v_incomplete_count;
  END IF;

  IF p_verifier_id IS NOT NULL THEN
    SELECT id, email, role INTO v_verifier FROM public.users WHERE id = p_verifier_id;
  END IF;

  UPDATE public.tasks
  SET status = 'VERIFIED',
      verified_at = now(),
      verified_by = p_verifier_id,
      verification_notes = COALESCE(p_notes, 'Verified during final issue resolution'),
      updated_at = now()
  WHERE civic_issue_id = p_civic_issue_id AND status = 'COMPLETED';

  UPDATE public.workstreams
  SET status = 'COMPLETED', updated_at = now()
  WHERE civic_issue_id = p_civic_issue_id AND status != 'CANCELLED';

  UPDATE public.civic_issues
  SET status = 'VERIFIED',
      resolved_at = now(),
      verified_at = now(),
      verified_by = p_verifier_id,
      verification_notes = p_notes,
      updated_at = now()
  WHERE id = p_civic_issue_id;

  UPDATE public.complaints
  SET status = 'Resolved', updated_at = now()
  WHERE civic_issue_id = p_civic_issue_id;

  RETURN jsonb_build_object(
    'success', true,
    'civic_issue_id', p_civic_issue_id,
    'status', 'VERIFIED',
    'verified_by', p_verifier_id,
    'verified_at', now(),
    'notes', p_notes
  );
END;
$$;

-- Gate 1 database permissions (canonical migration in supabase/migrations)
-- Gate 1: GrievanceIQ uses custom application JWTs through Express.
-- These tables, views and RPCs are backend-only, including public-feed reads.
-- Safe to run before the feature upgrade for existing objects and again after it.
-- PostgreSQL 15+ required for security_invoker views (selected staging uses 17).
BEGIN;

DO $permissions$
DECLARE object_name text; role_name text; fn record;
BEGIN
  FOREACH object_name IN ARRAY ARRAY[
    'users','complaints','departments','civic_issues','complaint_relationships',
    'workstreams','tasks','routing_results','task_dependencies','task_status_history',
    'wicr_decisions','wicr_review_events','task_dependency_recommendations'
  ] LOOP
    IF to_regclass(format('public.%I',object_name)) IS NULL THEN CONTINUE; END IF;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',object_name);
    -- The observed legacy policy is TO public USING (true), despite its name.
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I','Enable all access for service_role',object_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',object_name);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',object_name,role_name);
      END IF;
    END LOOP;
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO service_role',object_name);
    END IF;
  END LOOP;

  FOREACH object_name IN ARRAY ARRAY[
    'v_pending_wicr_reviews','v_pending_dependency_recommendations','v_civic_issue_related_links'
  ] LOOP
    IF to_regclass(format('public.%I',object_name)) IS NULL THEN CONTINUE; END IF;
    EXECUTE format('ALTER VIEW public.%I SET (security_invoker=true)',object_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC',object_name);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM %I',object_name,role_name);
      END IF;
    END LOOP;
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
      EXECUTE format('GRANT SELECT ON TABLE public.%I TO service_role',object_name);
    END IF;
  END LOOP;

  -- Handle every overload of the named application functions, including future
  -- signature changes. Do not alter extension-owned or unrelated functions.
  FOR fn IN SELECT p.oid::regprocedure AS signature FROM pg_proc p
    JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.proname=ANY(ARRAY[
      'acquire_complaint_lease','renew_complaint_lease','commit_complaint_processing',
      'record_complaint_failure','commit_complaint_pipeline_transaction',
      'get_related_civic_issues','check_improper_civic_issue_groupings',
      'add_task_dependency_transactional','check_task_cycle_trigger',
      'update_task_status_transactional','record_wicr_decision','resolve_wicr_review',
      'prevent_wicr_event_mutation','accept_dependency_recommendation',
      'reject_dependency_recommendation','verify_civic_issue_resolution'
    ]) LOOP
    EXECUTE format('ALTER FUNCTION %s SECURITY INVOKER',fn.signature);
    EXECUTE format('ALTER FUNCTION %s SET search_path = %L',fn.signature,'');
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC',fn.signature);
    FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
      IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
        EXECUTE format('REVOKE ALL ON FUNCTION %s FROM %I',fn.signature,role_name);
      END IF;
    END LOOP;
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
      EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role',fn.signature);
    END IF;
  END LOOP;

  -- Defaults apply to objects subsequently created by this migration's owner.
  -- PUBLIC function EXECUTE is a global default and requires a global revoke;
  -- a schema-scoped revoke alone does not remove that inherited default.
  ALTER DEFAULT PRIVILEGES REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
  ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM PUBLIC;
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('ALTER DEFAULT PRIVILEGES REVOKE EXECUTE ON FUNCTIONS FROM %I',role_name);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE EXECUTE ON FUNCTIONS FROM %I',role_name);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM %I',role_name);
    END IF;
  END LOOP;
END
$permissions$;

NOTIFY pgrst, 'reload schema';
COMMIT;
